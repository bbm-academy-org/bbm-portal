-- ---------------------------------------------------------------------------
-- 6. The backfill, from the change journal
-- ---------------------------------------------------------------------------
--
-- Every row that predates this migration has `now()` in both timestamps and a
-- NULL actor — which would be a fabricated fact wherever the journal already
-- knows better. `core.audit_event` has held one row per write since `0003`, so
-- for a row it covers the answer is already recorded:
--
--   * `created_at` / `created_by` <- the row's OWN `data.<table>.insert` event
--     for that primary key (the most recent one — see the DESC note below);
--   * `updated_at` / `updated_by` <- the LATEST event of ANY type for it.
--
-- **What the journal may and may not touch.** The journal FILLS A GAP; it never
-- overwrites a value the row already carries. Four of these columns are new on
-- nineteen tables and were already there on three, and the difference is not
-- cosmetic: `finance_counterparty.created_by` and `finance_intake_item.created_by`
-- mean «the SUBMITTER», not «who executed the INSERT». For a request filed on
-- someone's behalf — which is the whole of the reconstructed population #517
-- describes — those are two different people, the journal holds the operator,
-- and the column holds the person the request is for. A backfill preferring the
-- journal would rewrite the requester with the importer, on a value the finance
-- board renders. So `created_by` and `updated_by` are
-- `coalesce(<the row's value>, <the journal's>)`: stored first, journal second.
-- No table carries a pre-existing `updated_by` today; the rule is written for
-- both columns anyway, because the next table to arrive with one must not
-- depend on this migration being re-read.
--
-- The two TIMESTAMPS cannot use the same shape, because they are NOT NULL with
-- a default: `r.created_at` is never null, so a plain `coalesce` in that order
-- would disable half the backfill outright. The honest question is «was this
-- column added by THIS migration?», and the answer is in the value itself: the
-- `ADD COLUMN … DEFAULT now()` block above stamps every pre-existing row with
-- `now()`, which inside one transaction is `transaction_timestamp()` — the same
-- instant this UPDATE reads. So `r.created_at = now()` is true exactly for a
-- column this migration created, and false for one that arrived with real data
-- earlier. Today that resolves to three exceptions preserved untouched:
-- `member.created_at`, `member.updated_at`, `finance_counterparty.created_at`
-- and `finance_purpose_proposal.created_at`. The issue's own acceptance line —
-- «existing per-table `created_at` / `updated_at` moved onto the helper WITHOUT
-- DATA LOSS» — is what this clause satisfies.
--
-- `actor_email` is mapped to `core.member.id`; an email no member carries (a
-- departed person, a `db-direct` write) yields NULL rather than a guess. A row
-- the journal does not cover keeps the `now()` default and a NULL actor — the
-- honest «we do not know», never the migration's own clock dressed as a fact.
-- The known consequence, stated in #516 itself: the 47 reconstructed requests
-- get their RECONSTRUCTION date, and #517 lifts the real filing date from the
-- note's `source_created_at` line on top of this.
--
-- **The primary key join is catalog-driven.** `audit_event.pk` is a jsonb
-- object keyed by the table's real PK columns (`0003` reads them from
-- `pg_index`), so a composite key and a text key (`finance_currency.code`) need
-- no per-table code here either: every PK column is compared as text against
-- `pk->>'<column>'`.
--
-- **User triggers are OFF for the backfill, and that is the whole point.** Left
-- on, this block would do two wrong things at once: the stamping trigger of
-- section 3 would overwrite every value being restored with `now()`, and the
-- capture trigger would append ~one `db-direct` UPDATE event per existing row —
-- flooding the very journal being read with entries recording nothing but this
-- migration. `ALTER TABLE … DISABLE TRIGGER USER` is the form used rather than
-- `session_replication_role = replica`: the latter needs superuser, and the
-- migration runs as `platform_migrator`, which merely OWNS these tables (#278).
-- Ownership is exactly what `DISABLE TRIGGER USER` requires.

DO $audit_columns_backfill$
DECLARE
	rec        record;
	pk_cols    text[];
	join_cond  text;
	first_ev   text;
	last_ev    text;
BEGIN
	FOR rec IN
		SELECT cls.oid, cls.relname AS table_name
		FROM pg_class cls
		JOIN pg_namespace nsp ON nsp.oid = cls.relnamespace
		WHERE nsp.nspname = 'core'
			AND cls.relkind = 'r'
			AND cls.relname NOT IN ('audit_event', '__drizzle_migrations')
		ORDER BY cls.relname
	LOOP
		SELECT array_agg(att.attname ORDER BY att.attnum)
		INTO pk_cols
		FROM pg_index idx
		JOIN pg_attribute att ON att.attrelid = idx.indrelid AND att.attnum = ANY (idx.indkey)
		WHERE idx.indrelid = rec.oid AND idx.indisprimary;

		-- A table with no primary key cannot be joined to the journal at all;
		-- its rows keep the default rather than being matched by guesswork.
		CONTINUE WHEN pk_cols IS NULL;

		SELECT string_agg(format('ev.pk->>%L is not distinct from (r.%I)::text', col, col), ' and ')
		INTO join_cond
		FROM unnest(pk_cols) AS col;

		first_ev := format(
			'select ev.created_at as at, (select m.id from core.member m where m.email = ev.actor_email) as actor'
			|| ' from core.audit_event ev where ev.table_name = %L and ev.event_type = %L and %s'
			-- DESC, i.e. the row's OWN insert rather than the oldest one ever
			-- recorded under that key. A primary key is reused after
			-- `TRUNCATE … RESTART IDENTITY`, which the integration tier and the
			-- dev seed both do, so the oldest insert event under key 7 can belong
			-- to a row that no longer exists. For a key that was inserted once —
			-- production, and every row this backfill actually cares about — the
			-- two orderings name the same event.
			|| ' order by ev.id desc limit 1',
			rec.table_name, 'data.' || rec.table_name || '.insert', join_cond);

		last_ev := format(
			'select ev.created_at as at, (select m.id from core.member m where m.email = ev.actor_email) as actor'
			|| ' from core.audit_event ev where ev.table_name = %L and %s'
			|| ' order by ev.id desc limit 1',
			rec.table_name, join_cond);

		EXECUTE format('ALTER TABLE core.%I DISABLE TRIGGER USER', rec.table_name);

		-- PRECEDENCE: a value the ROW already carries always wins; the journal
		-- only ever fills a gap. See the «What the journal may and may not
		-- touch» note above for why the two actor columns and the two
		-- timestamps need different shapes of the same rule.
		EXECUTE format(
			'UPDATE core.%1$I AS r SET'
			|| ' created_at = CASE WHEN r.created_at = now()'
			|| '                   THEN coalesce((select at from (%2$s) f), r.created_at)'
			|| '                   ELSE r.created_at END,'
			|| ' created_by = coalesce(r.created_by, (select actor from (%2$s) f)),'
			|| ' updated_at = CASE WHEN r.updated_at = now()'
			|| '                   THEN coalesce((select at from (%3$s) l), r.updated_at)'
			|| '                   ELSE r.updated_at END,'
			|| ' updated_by = coalesce(r.updated_by, (select actor from (%3$s) l))',
			rec.table_name, first_ev, last_ev);

		EXECUTE format('ALTER TABLE core.%I ENABLE TRIGGER USER', rec.table_name);
	END LOOP;
END
$audit_columns_backfill$;
