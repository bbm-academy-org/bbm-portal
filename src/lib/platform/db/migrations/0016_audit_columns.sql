-- ---------------------------------------------------------------------------
-- 1. `created_by` / `updated_by` are `core.member(id)` — the FKs, by hand
-- ---------------------------------------------------------------------------
--
-- Written here rather than declared in the schema files, because a drizzle
-- `.references(() => member.id)` in `schema/finance/` or `schema/hours/` would
-- import `schema/member/` into another module's schema directory — the import
-- ADR-004 §6 keeps out of a module. Same shape as
-- `finance_intake_item.created_by` and `finance_posting.member_id` (spec 338
-- EARS-322) already carry.
--
-- `ON DELETE SET NULL`: a member row disappearing must not take an invoice, a
-- ledger posting or a request with it. The attribution degrades to «nobody we
-- still have», which is the honest reading, and the JOURNAL still holds that
-- write's actor email — the two records are complementary, not redundant.
--
-- Catalog-driven and skip-if-present rather than 42 literal statements: two of
-- these columns (`finance_counterparty.created_by`,
-- `finance_intake_item.created_by`) already carry a FK from `0009`,
-- `ADD CONSTRAINT` has no `IF NOT EXISTS`, and a NOT NULL column cannot take
-- `ON DELETE SET NULL` at all.

DO $audit_columns_fk$
DECLARE
	rec record;
BEGIN
	FOR rec IN
		SELECT cls.relname AS table_name, att.attname AS column_name, att.attnotnull AS is_not_null
		FROM pg_class cls
		JOIN pg_namespace nsp ON nsp.oid = cls.relnamespace
		JOIN pg_attribute att ON att.attrelid = cls.oid
		WHERE nsp.nspname = 'core'
			AND cls.relkind = 'r'
			AND att.attname IN ('created_by', 'updated_by')
			AND att.attnum > 0
			AND NOT att.attisdropped
			AND NOT EXISTS (
				SELECT 1 FROM pg_constraint con
				WHERE con.conrelid = cls.oid
					AND con.contype = 'f'
					AND att.attnum = ANY (con.conkey)
			)
		ORDER BY cls.relname, att.attname
	LOOP
		EXECUTE format(
			'ALTER TABLE core.%I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES core.member(id) ON DELETE %s',
			rec.table_name,
			rec.table_name || '_' || rec.column_name || '_member_fk',
			rec.column_name,
			-- A NOT NULL column cannot be nulled by a cascade; it keeps the
			-- default NO ACTION, which is the only truthful option there.
			CASE WHEN rec.is_not_null THEN 'NO ACTION' ELSE 'SET NULL' END
		);
	END LOOP;
END
$audit_columns_fk$;--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- 2. The capture function gains ONE line (spec 201 EARS-2, EARS-3)
-- ---------------------------------------------------------------------------
--
-- Re-emitted whole, because `CREATE OR REPLACE FUNCTION` is how PL/pgSQL is
-- amended; the only difference from `0003_universal_edit_audit.sql` is the
-- bookkeeping skip, which now covers `updated_by` beside `updated_at`. The
-- comment at that line carries the reason.

CREATE OR REPLACE FUNCTION "core"."audit_row_change"() RETURNS trigger
	LANGUAGE plpgsql
	SECURITY DEFINER
	SET search_path = pg_catalog, core
AS $$
DECLARE
	whitelist   text[] := TG_ARGV;
	old_row     jsonb;
	new_row     jsonb;
	row_diff    jsonb := '{}'::jsonb;
	column_name text;
	old_value   jsonb;
	new_value   jsonb;
	pk_value    jsonb;
	actor       text;
	src         text;
	app_marked  boolean;
BEGIN
	-- --- attribution (EARS-6, EARS-7, EARS-8, EARS-26) ---------------------
	--
	-- `current_setting(name, true)` — the TWO-argument form, which returns NULL
	-- for an unset GUC instead of erroring, so the refusal below is OUR message
	-- and not Postgres's «unrecognized configuration parameter».
	actor      := nullif(current_setting('app.actor_email', true), '');
	src        := nullif(current_setting('app.source', true), '');
	app_marked := nullif(current_setting('app.connection', true), '') = 'app';

	IF src IS NULL THEN
		-- No context. WHOSE connection is it? The application's pool marks every
		-- socket it opens (`-c app.connection=app`, src/lib/platform/db/client.ts);
		-- a psql session, the drizzle-kit migration runner and a restore do not.
		IF app_marked THEN
			RAISE EXCEPTION
				'audit: actor context not set for %.% — an application write must run through platformTransaction(ctx, …), which issues set_config(''app.actor_email'', …, true) and set_config(''app.source'', …, true) inside the transaction (spec 201 EARS-24, EARS-26)',
				TG_TABLE_SCHEMA, TG_TABLE_NAME;
		END IF;
		-- Unmarked connection: somebody worked on the database directly. Append
		-- the row, degrade the attribution, never fabricate an actor (EARS-8).
		src   := 'db-direct';
		actor := NULL;
	ELSE
		-- The closed set of EARS-7. `db-direct` is the trigger's OWN fallback and
		-- is not a value any caller may set — letting an app write borrow it would
		-- make the ledger lie about the door the change came through.
		IF src !~ '^(portal|migration|manual-dba|system:[a-z0-9][a-z0-9._-]*|cli:[a-z0-9][a-z0-9._-]*)$' THEN
			RAISE EXCEPTION
				'audit: app.source «%» is not in the closed set portal | system:<job> | cli:<name> | migration | manual-dba (spec 201 EARS-7); db-direct is the trigger''s own fallback and cannot be set by a caller',
				src;
		END IF;
		-- The actor is required only where a human exists (EARS-7, EARS-9).
		IF src = 'portal' AND actor IS NULL THEN
			RAISE EXCEPTION
				'audit: app.source = ''portal'' means an authenticated request, so app.actor_email must be set (spec 201 EARS-7, EARS-9)';
		END IF;
	END IF;

	-- --- the diff (EARS-2, EARS-3, EARS-16, EARS-27) -----------------------
	IF TG_OP = 'INSERT' THEN
		new_row := to_jsonb(NEW);
	ELSIF TG_OP = 'DELETE' THEN
		old_row := to_jsonb(OLD);
	ELSE
		old_row := to_jsonb(OLD);
		new_row := to_jsonb(NEW);
	END IF;

	FOR column_name IN
		SELECT jsonb_object_keys(coalesce(new_row, old_row))
	LOOP
		-- `updated_at` and `updated_by` are bookkeeping, not a change (EARS-2).
		-- Since #516 EVERY `core` table carries both, written by
		-- `core.audit_columns_stamp()` below rather than by any caller. Naming
		-- either in a whitelist would grant a value that can never be written,
		-- and recording `updated_by` would ALSO break EARS-3: a touch by a
		-- different person changes that column and nothing else, so the ledger
		-- would gain a row for a change that never happened. The actor of the
		-- change is already this row's own `actor_email`.
		CONTINUE WHEN column_name IN ('updated_at', 'updated_by');

		old_value := old_row -> column_name;
		new_value := new_row -> column_name;

		-- An UPDATE records only what actually changed; a touch is not a change.
		CONTINUE WHEN TG_OP = 'UPDATE' AND old_value IS NOT DISTINCT FROM new_value;

		IF column_name = ANY (whitelist) THEN
			IF TG_OP = 'INSERT' THEN
				row_diff := row_diff || jsonb_build_object(column_name, jsonb_build_object('new', new_value));
			ELSIF TG_OP = 'DELETE' THEN
				row_diff := row_diff || jsonb_build_object(column_name, jsonb_build_object('old', old_value));
			ELSE
				row_diff := row_diff || jsonb_build_object(column_name, jsonb_build_object('old', old_value, 'new', new_value));
			END IF;
		ELSE
			-- Default-deny: the FACT of the change is in the ledger, the value
			-- never is — on INSERT, UPDATE and DELETE alike (EARS-2, EARS-27).
			row_diff := row_diff || jsonb_build_object(column_name, jsonb_build_object('changed', true));
		END IF;
	END LOOP;

	-- Nothing changed after those rules: write NO row. The trail records
	-- changes, not touches (EARS-3).
	IF TG_OP = 'UPDATE' AND row_diff = '{}'::jsonb THEN
		RETURN NULL;
	END IF;

	-- --- the primary key, from the catalog (EARS-4) -------------------------
	--
	-- Read from `pg_index`/`pg_attribute` on TG_RELID rather than from a
	-- per-table list, so a COMPOSITE primary key is carried with no per-table
	-- code — for tables that do not exist yet as much as for the six that do.
	SELECT jsonb_object_agg(att.attname, coalesce(new_row, old_row) -> att.attname)
	INTO pk_value
	FROM pg_index idx
	JOIN pg_attribute att
		ON att.attrelid = idx.indrelid
		AND att.attnum = ANY (idx.indkey)
	WHERE idx.indrelid = TG_RELID
		AND idx.indisprimary;

	INSERT INTO core.audit_event
		(event_type, table_name, actor_email, source, pk, diff, txid)
	VALUES (
		'data.' || TG_TABLE_NAME || '.' || lower(TG_OP),
		TG_TABLE_NAME,
		actor,
		src,
		coalesce(pk_value, '{}'::jsonb),
		row_diff,
		-- `pg_current_xact_id()`, not the wrapping 32-bit `txid_current()`: this
		-- column is a GROUPING key, so every row written by one save is grouped.
		pg_current_xact_id()::text
	);

	-- AFTER trigger: the return value is ignored, and NULL says so.
	RETURN NULL;
END;
$$;--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- 3. The stamping function
-- ---------------------------------------------------------------------------
--
-- Maintenance of the four columns is a DATABASE TRIGGER, not the write layer.
-- The alternative — every caller setting `updated_at` — was rejected because a
-- `cli:*` script, a fixture, a seed and a hand-run `psql` statement are all
-- legitimate writers here, and the one that forgets is exactly the one whose
-- row later reads as untouched. One trigger attributes all of them identically.
--
-- The ACTOR comes from the SAME session variable the journal reads —
-- `app.actor_email`, set by `platformTransaction()` — resolved to
-- `core.member.id`. So the row's `created_by` and the ledger's `actor_email`
-- cannot disagree about who wrote it. When the GUC is unset (an unmarked
-- connection: psql, the migration runner, a restore) or names an email no
-- member carries, the actor is NULL and the row still lands: refusing a
-- context-less write is already `core.audit_row_change()`'s job (EARS-26), and
-- a second refusal for one cause would only make the message worse.
--
-- `created_at` / `created_by` are IMMUTABLE: on UPDATE they are restored from
-- OLD, so an accidental `set created_by = …` cannot rewrite provenance.
--
-- On INSERT both are `coalesce(<what the caller wrote>, <the actor>)` rather
-- than the actor outright. `finance_intake_item.created_by` is the SUBMITTER —
-- for a backfilled request that is the person who filed it, not the operator
-- running the import — so overwriting an explicitly supplied value would lose
-- the fact the column exists to carry.
--
-- `SECURITY DEFINER` with a pinned `search_path`, like the capture function
-- beside it: this function reads `core.member`, and the pinned path is what
-- closes the search-path hijack `SECURITY DEFINER` otherwise opens.

CREATE OR REPLACE FUNCTION "core"."audit_columns_stamp"() RETURNS trigger
	LANGUAGE plpgsql
	SECURITY DEFINER
	SET search_path = pg_catalog, core
AS $$
DECLARE
	actor_id integer;
BEGIN
	SELECT m.id INTO actor_id
	FROM core.member m
	WHERE m.email = nullif(current_setting('app.actor_email', true), '');

	IF TG_OP = 'INSERT' THEN
		NEW.created_at := coalesce(NEW.created_at, now());
		NEW.created_by := coalesce(NEW.created_by, actor_id);
		NEW.updated_at := now();
		-- The session actor, never a copy of `created_by`. The two answer
		-- different questions: `created_by` is WHO THE ROW IS FOR where a caller
		-- supplied it (the submitter of a request filed on someone's behalf),
		-- while `updated_by` is WHO LAST WROTE IT. Copying the first into the
		-- second would name a person who never touched the row — the same
		-- fabrication the NULL-actor rule above refuses, arrived at from the
		-- other direction. A NULL here is the truthful answer for an unmarked
		-- connection, exactly as it is on the UPDATE arm.
		NEW.updated_by := actor_id;
	ELSE
		-- Immutable: whatever the statement said about these two, the row keeps
		-- what it was created with.
		NEW.created_at := OLD.created_at;
		NEW.created_by := OLD.created_by;
		NEW.updated_at := now();
		NEW.updated_by := actor_id;
	END IF;

	RETURN NEW;
END;
$$;--> statement-breakpoint

