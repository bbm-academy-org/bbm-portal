/**
 * Лоадер: `.mdx` втягивается в бандл ТЕКСТОМ, а не компилируется.
 *
 * В этом репо .mdx-файл ровно один — снимок нормативного документа финмодели
 * `src/lib/finmodel/snapshot/rules.mdx` (#193). Его компилирует не бандлер, а
 * рендерер страницы (`next-mdx-remote/rsc`), потому что подстановка `<V/>`
 * должна происходить на сервере со значениями снапшота, а не на сборке.
 *
 * Почему лоадер, а не `readFileSync`: `output: 'standalone'` кладёт в образ
 * только трассированные модули, `src/` в него не попадает — чтение с диска
 * собралось бы локально и упало бы в проде на первом запросе.
 *
 * Почему лоадер, а не `?raw`: Turbopack (сборщик `next build` в Next 16) на
 * `./x.mdx?raw` отвечает «Unknown module type» — запрос он не обрабатывает.
 * Лоадер понимают оба сборщика Next; у vitest своя, третья декларация того же
 * факта (`vitest.config.mts`), потому что документ читает ещё и тест
 * согласованности.
 *
 * @param {string} source
 * @returns {string}
 */
module.exports = function mdxRawLoader(source) {
  return `export default ${JSON.stringify(source)}\n`
}
